/** Units of `to` for 1 unit of `from`, as an annual average in `year`; null when either currency has no rate that year. */
export function historicalRate(from: string, to: string, year: number): number | null {
  const perUsd = (code: string) => (code === "USD" ? 1 : PER_USD[code]?.[year]);
  const a = perUsd(from);
  const b = perUsd(to);
  if (a === undefined || b === undefined) return null;
  return b / a;
}
